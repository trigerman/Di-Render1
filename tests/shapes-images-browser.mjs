import assert from 'node:assert/strict';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {chromium} from '../app/node_modules/playwright/index.mjs';

const browser = await chromium.launch({headless:true});
const context = await browser.newContext({viewport:{width:1500,height:1000},acceptDownloads:true});
const page = await context.newPage();
page.setDefaultTimeout(8000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => {if (message.type()==='error') errors.push(message.text());});
const directory = 'reports/shapes-images';
const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
await mkdir(directory,{recursive:true});
const save = async () => {
  const pending=page.waitForEvent('download');
  await page.getByTestId('save-project').click();
  const download=await pending;
  return JSON.parse(await readFile(await download.path(),'utf8'));
};
const insertShape = async name => {
  await page.locator('.shape-gallery summary').click();
  await page.getByRole('searchbox',{name:'Search shapes'}).fill(name);
  await page.getByRole('button',{name:`Insert ${name}`,exact:true}).click();
};
try {
  await page.goto('http://127.0.0.1:4173');
  await page.getByRole('button',{name:'New figure',exact:true}).click();
  await page.getByRole('button',{name:'Create figure',exact:true}).click();
  await page.getByTestId('workspace').waitFor();
  await insertShape('Right block arrow');
  await page.getByLabel('Layer name').fill('Source');
  await page.getByLabel('Shape text').fill('Signal');
  await page.getByLabel(/Adjust shape/).press('End');
  await insertShape('Process');
  await page.getByLabel('Layer name').fill('Target');
  await page.getByLabel('X',{exact:true}).fill('900');
  await page.getByRole('button',{name:'More drawing tools'}).click();
  await page.getByRole('menuitem',{name:'Add connector'}).click();
  await page.getByLabel('Start object').selectOption({label:'Source'});
  await page.getByLabel('End object').selectOption({label:'Target'});
  await page.getByLabel('Route').selectOption('elbow');
  let project=await save();
  const connector=project.objects.find(object => object.kind==='connector');
  assert.equal(connector.start.objectId, project.objects.find(object=>object.name==='Source').id);
  assert.equal(connector.end.objectId, project.objects.find(object=>object.name==='Target').id);
  assert.equal(connector.routing,'elbow');
  const prior=connector.points.slice();
  await page.getByRole('tab',{name:/^Layers/}).click();
  await page.getByRole('button',{name:'Source shape'}).click();
  await page.getByRole('tab',{name:'Style',exact:true}).click();
  await page.getByLabel('X',{exact:true}).fill('350');
  project=await save();
  assert.notDeepEqual(project.objects.find(object=>object.kind==='connector').points, prior);
  const png=await page.locator('canvas.lower-canvas').evaluate(canvas=>canvas.toDataURL('image/png').split(',')[1]);
  await page.locator('input[type=file][accept*=".png"]').setInputFiles({name:'local.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
  assert.equal((await save()).media.length,1);
  await page.getByTestId('undo').click();
  await page.locator('.toast').filter({hasText:'Undo'}).waitFor();
  assert.equal((await save()).media.length,0);
  await page.getByTestId('redo').click();
  await page.locator('.toast').filter({hasText:'Redo'}).waitFor();
  assert.equal((await save()).media.length,1);
  await page.getByRole('tab',{name:/^Layers/}).click();
  await page.getByRole('button',{name:'local.png image'}).click();
  await page.getByRole('tab',{name:'Style',exact:true}).click();
  await page.getByLabel('Crop X').fill('10');
  project=await save();
  assert.equal(project.media.length,1);
  assert.equal(project.objects.find(object=>object.kind==='image').cropX,10);
  await page.locator('canvas.upper-canvas').click({position:{x:10,y:10}});
  await frame();
  const before=await page.locator('canvas.lower-canvas').evaluate(canvas=>canvas.toDataURL());
  await page.screenshot({path:directory+'/figure.png',fullPage:true});
  await page.locator('input[type=file][accept*=".obf"]').setInputFiles({name:'roundtrip.obf.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))});
  await page.getByText('Project opened',{exact:true}).waitFor();
  await frame();
  const after=await page.locator('canvas.lower-canvas').evaluate(canvas=>canvas.toDataURL());
  if (after!==before) {
    await writeFile(directory+'/before.png',Buffer.from(before.split(',')[1],'base64'));
    await writeFile(directory+'/after.png',Buffer.from(after.split(',')[1],'base64'));
    const reopened=await save();
    console.error('BEFORE MODEL', project.objects.map(({id,name,kind,x,y,width,height,scaleX,scaleY,points,cropX,cropWidth})=>({id,name,kind,x,y,width,height,scaleX,scaleY,points,cropX,cropWidth})));
    console.error('AFTER MODEL', reopened.objects.map(({id,name,kind,x,y,width,height,scaleX,scaleY,points,cropX,cropWidth})=>({id,name,kind,x,y,width,height,scaleX,scaleY,points,cropX,cropWidth})));
    throw new Error('Portable reopen changed rendered pixels: '+[before,after].map(value=>createHash('sha256').update(value).digest('hex')).join(' vs '));
  }
  const reopened=await save();
  assert.deepEqual(reopened.objects.find(object=>object.kind==='connector').start,connector.start);
  assert.equal(reopened.media[0].data,project.media[0].data);
  await page.getByText('Saved locally',{exact:true}).waitFor();
  await page.reload();
  await page.getByTestId('workspace').waitFor();
  await frame();
  assert.equal(await page.locator('canvas.lower-canvas').evaluate(canvas=>canvas.toDataURL()),before);
  assert.equal((await save()).media[0].data,project.media[0].data);
  const pending=page.waitForEvent('download');
  await page.getByTestId('export-svg').click();
  const svg=(await readFile(await (await pending).path(),'utf8'));
  assert.match(svg,/<image/);
  assert.match(svg,/data:image\/png;base64,/);
  const pngDownload=page.waitForEvent('download');
  await page.getByTestId('export-png').click();
  const pngOutput=await readFile(await (await pngDownload).path());
  assert.equal(pngOutput.readUInt32BE(16),2400);
  assert.equal(pngOutput.readUInt32BE(20),1600);
  await page.evaluate(()=>{window.print=()=>{};});
  await page.getByTestId('export-pdf').click();
  await page.locator('#publication-print image').waitFor({state:'attached'});
  assert.equal(await page.locator('#publication-print image').count(),1);
  await page.locator('.shape-gallery summary').click();
  await page.getByRole('searchbox',{name:'Search shapes'}).fill('');
  await page.screenshot({path:directory+'/gallery.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS shape gallery, attached connector, image crop and undo, portable reopen, SVG/PNG/PDF output');
} catch (error) {
  console.error('BROWSER ERRORS', errors);
  await page.screenshot({path:directory+'/failure.png',fullPage:true});
  throw error;
} finally { await browser.close(); }
